/**
 * ClientMaster
 * Client organization master: list with search/status filter and
 * pagination, detail modal with linked logins, create/edit modal,
 * deactivate with confirmation, optional login provisioning.
 *
 * The create/edit form matches the redesigned registration form:
 *   01 Client Information        (blue)   - logo, name, GST number
 *   02 Address Information       (green)  - address lines, state, district,
 *                                          city, police station, PIN, landmark
 *   03 Contact Person Details    (amber)  - name, phone, email
 *   04 Client Information Status (violet) - Active/Inactive + remarks
 * client_code is auto-generated by the backend (CLT-FIRST3-### — first 3
 * letters of the client name + serial) and never shown on the form. Logo uploads
 * go through the multipart POST/PUT alongside the other fields.
 * Fields match the live `clients` schema (migration 024). Actions gated
 * by hasPermission(); the backend requirePermission middleware stays
 * authoritative.
 */
import React, { useState, useEffect, useCallback } from "react";
import { useAuth } from "../context/AuthContext";
import ClientService from "../services/ClientService";
import ResetPasswordModal from "./ResetPasswordModal";
import api from "../services/api";
import { StateSelect, DistrictSelect } from "./StateDistrictSelect";

const emptyForm = {
  client_code: "", // echo-only (edit); generated by backend on create
  client_name: "",
  gst_number: "",
  address_line_1: "",
  address_line_2: "",
  state: "",
  district: "",
  city: "",
  police_station: "",
  pincode: "",
  landmark: "",
  contact_person: "",
  phone: "",
  email: "",
  status: "Active",
  remarks: ""
};

// Absolute URL for uploaded files (logo etc.) from a relative
// uploads/... path. Derives scheme://host[:port] from the axios baseURL
// so it works with localhost, LAN IP and REACT_APP_API_URL overrides.
const UPLOAD_URL_BASE = (() => {
  try {
    const parsed = new URL(api.defaults?.baseURL || "");
    return `${parsed.protocol}//${parsed.host}`;
  } catch (_) {
    return "";
  }
})();

const GSTIN_RE = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][0-9A-Z]Z[0-9A-Z]$/;
const MAX_LOGO_BYTES = 2 * 1024 * 1024; // matches backend limit

// Build a full URL for a relative uploads/clients/... path.
const logoUrl = (relPath) =>
  `${UPLOAD_URL_BASE}/${String(relPath || "").replace(/^\//, "")}`;

const ClientMaster = () => {
  const { hasPermission } = useAuth();
  // Admin module uses the granular clients.view.all (no generic
  // clients.view exists by design — see 010 migration).
  const canView = hasPermission("clients.view.all");
  const canCreate = hasPermission("clients.create");
  const canUpdate = hasPermission("clients.update");
  const canDeactivate = hasPermission("clients.delete");
  const canResetPassword = hasPermission("users.password.reset");

  const [clients, setClients] = useState([]);
  const [pagination, setPagination] = useState({ page: 1, limit: 20, total: 0, totalPages: 0 });
  const [filters, setFilters] = useState({ search: "", status: "" });
  const [searchInput, setSearchInput] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [alert, setAlert] = useState({ show: false, type: "", message: "" });

  const [showForm, setShowForm] = useState(false);
  const [editing, setEditing] = useState(null);
  const [formData, setFormData] = useState(emptyForm);
  const [formErrors, setFormErrors] = useState({});
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [logoFile, setLogoFile] = useState(null);
  const [logoPreview, setLogoPreview] = useState(null);

  const [detail, setDetail] = useState(null);

  const [showLoginForm, setShowLoginForm] = useState(false);
  const [loginData, setLoginData] = useState({ username: "", email: "", password: "" });
  const [isCreatingLogin, setIsCreatingLogin] = useState(false);
  const [resetTarget, setResetTarget] = useState(null);

  const showAlert = (type, message) => {
    setAlert({ show: true, type, message });
    setTimeout(() => setAlert({ show: false, type: "", message: "" }), 5000);
  };

  const loadClients = useCallback(
    async (page = 1, overrideFilters = null) => {
      const f = overrideFilters || filters;
      setIsLoading(true);
      try {
        const res = await ClientService.getClients({ ...f, page, limit: 20 });
        if (res.success) {
          setClients(res.data);
          setPagination(res.pagination);
        } else {
          showAlert("danger", res.message || "Failed to load clients.");
        }
      } catch (error) {
        showAlert("danger", error.response?.data?.message || "Unable to load clients.");
      } finally {
        setIsLoading(false);
      }
    },
    [filters]
  );

  useEffect(() => {
    if (canView) loadClients(1);
  }, [canView, loadClients]);

  const applyFilters = (e) => {
    e.preventDefault();
    loadClients(1, { ...filters, search: searchInput });
    setFilters((prev) => ({ ...prev, search: searchInput }));
  };

  const clearFilters = () => {
    const cleared = { search: "", status: "" };
    setFilters(cleared);
    setSearchInput("");
    loadClients(1, cleared);
  };

  const openCreate = () => {
    setEditing(null);
    setFormData(emptyForm);
    setFormErrors({});
    setLogoFile(null);
    setLogoPreview(null);
    setShowForm(true);
  };

  const openEdit = (cli) => {
    setEditing(cli);
    setFormData({
      client_code: cli.client_code || "",
      client_name: cli.client_name || "",
      gst_number: cli.gst_number || "",
      // Legacy rows only had the free-text `address` column — show it
      // as line 1 so old records edit seamlessly.
      address_line_1: cli.address_line_1 || cli.address || "",
      address_line_2: cli.address_line_2 || "",
      state: cli.state || "",
      district: cli.district || "",
      city: cli.city || "",
      police_station: cli.police_station || "",
      pincode: cli.pincode || "",
      landmark: cli.landmark || "",
      contact_person: cli.contact_person || "",
      phone: cli.phone || "",
      email: cli.email || "",
      status: cli.status || "Active",
      remarks: cli.remarks || ""
    });
    setFormErrors({});
    setLogoFile(null);
    setLogoPreview(cli.logo_path ? logoUrl(cli.logo_path) : null);
    setShowForm(true);
  };

  const handleLogoChange = (e) => {
    const file = e.target.files && e.target.files[0];
    if (!file) { setLogoFile(null); setLogoPreview(editing?.logo_path ? logoPreview : null); return; }
    if (file.size > MAX_LOGO_BYTES) {
      showAlert("danger", "Logo must be 2 MB or smaller.");
      e.target.value = "";
      return;
    }
    setLogoFile(file);
    setLogoPreview(URL.createObjectURL(file));
  };

  const validateForm = () => {
    const errs = {};
    if (!formData.client_name.trim()) errs.client_name = "Client Name is required.";
    const gst = formData.gst_number.trim().toUpperCase();
    if (gst && !GSTIN_RE.test(gst)) errs.gst_number = "Enter a valid 15-character GSTIN.";
    if (!formData.address_line_1.trim()) errs.address_line_1 = "Address Line 1 is required.";
    if (!formData.city.trim()) errs.city = "City is required.";
    if (!formData.state.trim()) errs.state = "State is required.";
    if (formData.state.trim() && !formData.district.trim()) errs.district = "District is required.";
    if (!formData.contact_person.trim()) errs.contact_person = "Contact Person Name is required.";
    if (!formData.phone.trim()) {
      errs.phone = "Phone Number is required.";
    } else {
      const digits = formData.phone.replace(/\D/g, "");
      if (digits.length < 10 || digits.length > 13) errs.phone = "Phone must be a valid 10-digit number.";
    }
    if (!formData.email.trim()) {
      errs.email = "Email ID is required.";
    } else if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(formData.email.trim())) {
      errs.email = "Invalid email format.";
    }
    const pincode = formData.pincode.trim();
    if (pincode && !/^[0-9]{6}$/.test(pincode)) errs.pincode = "PIN Code must be a 6-digit number.";
    setFormErrors(errs);
    return Object.keys(errs).length === 0;
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!validateForm()) return;
    setIsSubmitting(true);
    try {
      const isMultipart = logoFile instanceof File;
      let payload;
      if (isMultipart) {
        payload = new FormData();
        Object.entries(formData).forEach(([k, v]) => {
          if (v !== undefined && v !== null) payload.append(k, String(v));
        });
        payload.append("logo", logoFile);
      } else {
        payload = { ...formData };
      }
      if (editing) {
        const res = await ClientService.updateClient(editing.id, payload);
        showAlert("success", res.message || "Client updated.");
      } else {
        const res = await ClientService.createClient(payload);
        showAlert("success", res.message || "Client created.");
      }
      setShowForm(false);
      loadClients(pagination.page);
      if (detail && editing && detail.id === editing.id) {
        const refreshed = await ClientService.getClientById(editing.id);
        if (refreshed.success) setDetail(refreshed.data);
      }
    } catch (error) {
      showAlert("danger", error.response?.data?.message || "Save failed.");
    } finally {
      setIsSubmitting(false);
    }
  };

  const openDetail = async (cli) => {
    try {
      const res = await ClientService.getClientById(cli.id);
      if (res.success) {
        setDetail(res.data);
        setShowLoginForm(false);
        setLoginData({ username: "", email: res.data.email || "", password: "" });
      }
    } catch (error) {
      showAlert("danger", error.response?.data?.message || "Could not load details.");
    }
  };

  const handleDeactivate = async (cli) => {
    if (!window.confirm(`Deactivate client "${cli.client_name}" (${cli.client_code})? Stores, jobs and history stay intact; linked logins will be locked.`)) return;
    try {
      const res = await ClientService.deactivateClient(cli.id);
      showAlert("success", res.message || "Deactivated.");
      setDetail(null);
      loadClients(pagination.page);
    } catch (error) {
      showAlert("danger", error.response?.data?.message || "Deactivation failed.");
    }
  };

  const handleCreateLogin = async (e) => {
    e.preventDefault();
    if (!loginData.username.trim() || loginData.username.trim().length < 3) {
      showAlert("danger", "Username required (min 3 characters).");
      return;
    }
    if (!loginData.password || loginData.password.length < 6) {
      showAlert("danger", "Password required (min 6 characters).");
      return;
    }
    setIsCreatingLogin(true);
    try {
      const res = await ClientService.createClientLogin(detail.id, loginData);
      showAlert("success", res.message || "Login created.");
      if (res.success) {
        setDetail(res.data);
        setShowLoginForm(false);
      }
    } catch (error) {
      showAlert("danger", error.response?.data?.message || "Login creation failed.");
    } finally {
      setIsCreatingLogin(false);
    }
  };

  const goPage = (page) => {
    if (page >= 1 && page <= Math.max(pagination.totalPages, 1)) loadClients(page);
  };

  if (!canView) {
    return (
      <div className="container mt-5">
        <div className="alert alert-danger">
          <i className="bi bi-shield-lock me-2"></i>
          Access denied. This page requires permission <strong>clients.view.all</strong>.
        </div>
      </div>
    );
  }

  return (
    <div className="dashboard-content">
      <div className="page-header">
        <div>
          <h4>Clients</h4>
          <p>Client organization master — {pagination.total} record(s). Deactivation preserves stores, jobs and history.</p>
        </div>
        {canCreate && (
          <button className="btn btn-primary" onClick={openCreate}>
            <i className="bi bi-plus-lg me-2"></i>Add Client
          </button>
        )}
      </div>

      {alert.show && (
        <div className={`alert alert-${alert.type} alert-dismissible fade show`} role="alert">
          {alert.message}
          <button type="button" className="btn-close" onClick={() => setAlert({ show: false, type: "", message: "" })}></button>
        </div>
      )}

      <div className="card shadow-sm border-0 mb-4">
        <div className="card-body">
          <form onSubmit={applyFilters}>
            <div className="row g-2 align-items-end">
              <div className="col-md-6">
                <label className="form-label">Search</label>
                <input
                  type="text" className="form-control" placeholder="Code, name, contact, phone, email..."
                  value={searchInput} onChange={(e) => setSearchInput(e.target.value)}
                />
              </div>
              <div className="col-md-3">
                <label className="form-label">Status</label>
                <select className="form-select" value={filters.status} onChange={(e) => setFilters({ ...filters, status: e.target.value })}>
                  <option value="">All</option>
                  <option value="Active">Active</option>
                  <option value="Inactive">Inactive</option>
                </select>
              </div>
              <div className="col-md-3 d-flex gap-2">
                <button type="submit" className="btn btn-primary"><i className="bi bi-search me-1"></i>Search</button>
                <button type="button" className="btn btn-outline-secondary" onClick={clearFilters} title="Clear filters">
                  <i className="bi bi-x-lg"></i>
                </button>
              </div>
            </div>
          </form>
        </div>
      </div>

      <div className="card shadow-sm border-0">
        <div className="card-body p-0">
          <div className="table-responsive">
            <table className="table table-hover align-middle mb-0 client-table">
              <thead>
                <tr>
                  <th className="ps-3">Code</th>
                  <th>Client Name</th>
                  <th>Contact</th>
                  <th>Phone</th>
                  <th>Status</th>
                  <th className="text-end pe-3">Actions</th>
                </tr>
              </thead>
              <tbody>
                {isLoading ? (
                  <tr><td colSpan="6" className="text-center py-4"><div className="spinner-border text-primary" role="status"></div></td></tr>
                ) : clients.length === 0 ? (
                  <tr><td colSpan="6" className="text-center py-4 text-muted">No clients found.</td></tr>
                ) : (
                  clients.map((cli) => (
                    <tr key={cli.id}>
                      <td className="ps-3"><span className="badge bg-light text-dark border font-monospace">{cli.client_code}</span></td>
                      <td className="fw-semibold">
                        <span className={`d-inline-flex align-items-center justify-content-center me-2 ${cli.logo_path ? "p-0" : "client-logo-thumb-placeholder"}`}
                          style={{ width: 28, height: 28, verticalAlign: "middle" }}>
                          {cli.logo_path
                            ? <img src={logoUrl(cli.logo_path)} alt="" className="client-logo-thumb" />
                            : <i className="bi bi-building"></i>}
                        </span>
                        {cli.client_name}
                      </td>
                      <td>{cli.contact_person || <span className="text-muted fst-italic">N/A</span>}</td>
                      <td>{cli.phone || <span className="text-muted fst-italic">N/A</span>}</td>
                      <td>
                        {cli.status === "Active"
                          ? <span className="badge-status-active"><i className="bi bi-check-circle-fill me-1"></i>Active</span>
                          : <span className="badge-status-inactive"><i className="bi bi-x-circle-fill me-1"></i>Inactive</span>}
                      </td>
                      <td className="text-end pe-3">
                        <div className="btn-group btn-group-sm">
                          <button className="btn btn-outline-secondary" onClick={() => openDetail(cli)} title="View">
                            <i className="bi bi-eye"></i>
                          </button>
                          {canUpdate && (
                            <button className="btn btn-outline-primary" onClick={() => openEdit(cli)} title="Edit">
                              <i className="bi bi-pencil"></i>
                            </button>
                          )}
                          {canDeactivate && cli.status === "Active" && (
                            <button className="btn btn-outline-danger" onClick={() => handleDeactivate(cli)} title="Deactivate">
                              <i className="bi bi-person-x"></i>
                            </button>
                          )}
                        </div>
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>
        {pagination.totalPages > 1 && (
          <div className="card-footer d-flex justify-content-center gap-2 bg-white">
            <button className="btn btn-sm btn-outline-secondary" disabled={pagination.page <= 1} onClick={() => goPage(pagination.page - 1)}>‹ Prev</button>
            <span className="align-self-center text-muted small">Page {pagination.page} of {pagination.totalPages} ({pagination.total} total)</span>
            <button className="btn btn-sm btn-outline-secondary" disabled={pagination.page >= pagination.totalPages} onClick={() => goPage(pagination.page + 1)}>Next ›</button>
          </div>
        )}
      </div>

      {showForm && (
        <div className="modal d-block client-form-backdrop" tabIndex="-1">
          <div className="modal-dialog client-form-dialog">
            <div className="modal-content">
              <div className="client-form-header">
                <div>
                  <h5 className="client-form-title">{editing ? "Edit Client" : "Client Registration"}</h5>
                  <p className="client-form-subtitle mb-0">Create and manage client registration information.</p>
                </div>
                <button type="button" className="btn-close" onClick={() => setShowForm(false)}></button>
              </div>
              <form onSubmit={handleSubmit}>
                <div className="modal-body client-form-body">

                  {/* ---- 01 Client Information --------------------------------- */}
                  <section className="client-section">
                    <div className="client-section-header cs-blue">
                      <span className="cs-chip"><i className="bi bi-building"></i></span>
                      <div>
                        <div className="cs-title">Client Information</div>
                        <div className="cs-subtitle">Company identity and registration details</div>
                      </div>
                      <span className="cs-number">01</span>
                    </div>
                    <div className="row g-3">
                      <div className="col-md-4">
                        <label className="form-label">Client Logo</label>
                        <div className="d-flex align-items-center gap-3">
                          <div className="client-logo-preview">
                            {logoPreview
                              ? <img src={logoPreview} alt="Client logo preview" />
                              : <i className="bi bi-image"></i>}
                          </div>
                          <div className="flex-grow-1">
                            <input
                              type="file"
                              className="form-control"
                              accept=".jpg,.jpeg,.png,.webp,.pdf,image/jpeg,image/png,image/webp,application/pdf"
                              onChange={handleLogoChange}
                            />
                            <div className="client-logo-hint">JPG, PNG or PDF • Maximum 2 MB</div>
                          </div>
                        </div>
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">Client Name <span className="text-danger">*</span></label>
                        <input type="text" className={`form-control ${formErrors.client_name ? "is-invalid" : ""}`}
                          value={formData.client_name} onChange={(e) => setFormData({ ...formData, client_name: e.target.value })} placeholder="Enter client name" />
                        {formErrors.client_name && <div className="invalid-feedback">{formErrors.client_name}</div>}
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">GST Number</label>
                        <input type="text" className={`form-control ${formErrors.gst_number ? "is-invalid" : ""}`}
                          value={formData.gst_number} onChange={(e) => setFormData({ ...formData, gst_number: e.target.value.toUpperCase() })}
                          placeholder="Enter GST registration number" maxLength={15} />
                        {formErrors.gst_number && <div className="invalid-feedback">{formErrors.gst_number}</div>}
                      </div>
                    </div>
                  </section>

                  {/* ---- 02 Address Information -------------------------------- */}
                  <section className="client-section">
                    <div className="client-section-header cs-green">
                      <span className="cs-chip"><i className="bi bi-geo-alt"></i></span>
                      <div>
                        <div className="cs-title">Address Information</div>
                        <div className="cs-subtitle">Registered and communication address</div>
                      </div>
                      <span className="cs-number">02</span>
                    </div>
                    <div className="row g-3">
                      <div className="col-md-6">
                        <label className="form-label">Address Line 1 <span className="text-danger">*</span></label>
                        <input type="text" className={`form-control ${formErrors.address_line_1 ? "is-invalid" : ""}`}
                          value={formData.address_line_1} onChange={(e) => setFormData({ ...formData, address_line_1: e.target.value })} placeholder="Enter address line 1" />
                        {formErrors.address_line_1 && <div className="invalid-feedback">{formErrors.address_line_1}</div>}
                      </div>
                      <div className="col-md-6">
                        <label className="form-label">Address Line 2</label>
                        <input type="text" className="form-control"
                          value={formData.address_line_2} onChange={(e) => setFormData({ ...formData, address_line_2: e.target.value })} placeholder="Enter address line 2" />
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">State <span className="text-danger">*</span></label>
                        <StateSelect
                          value={formData.state}
                          placeholder="Select state"
                          required
                          className={`form-select ${formErrors.state ? "is-invalid" : ""}`}
                          onChange={(v) => setFormData({ ...formData, state: v, district: "" })}
                        />
                        {formErrors.state && <div className="invalid-feedback">{formErrors.state}</div>}
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">District <span className="text-danger">*</span></label>
                        <DistrictSelect
                          stateName={formData.state}
                          value={formData.district}
                          placeholder="Select district"
                          className={`form-select ${formErrors.district ? "is-invalid" : ""}`}
                          onChange={(v) => setFormData({ ...formData, district: v })}
                        />
                        {formErrors.district && <div className="invalid-feedback">{formErrors.district}</div>}
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">City <span className="text-danger">*</span></label>
                        <input type="text" className={`form-control ${formErrors.city ? "is-invalid" : ""}`}
                          value={formData.city} onChange={(e) => setFormData({ ...formData, city: e.target.value })} placeholder="Enter city" />
                        {formErrors.city && <div className="invalid-feedback">{formErrors.city}</div>}
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">Police Station</label>
                        <input type="text" className="form-control"
                          value={formData.police_station} onChange={(e) => setFormData({ ...formData, police_station: e.target.value })} placeholder="Enter police station" />
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">PIN Code</label>
                        <input type="text" inputMode="numeric" className={`form-control ${formErrors.pincode ? "is-invalid" : ""}`}
                          value={formData.pincode}
                          onChange={(e) => setFormData({ ...formData, pincode: e.target.value.replace(/\D/g, "").slice(0, 6) })}
                          placeholder="Enter pin code" maxLength={6} />
                        {formErrors.pincode && <div className="invalid-feedback">{formErrors.pincode}</div>}
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">Landmark</label>
                        <input type="text" className="form-control"
                          value={formData.landmark} onChange={(e) => setFormData({ ...formData, landmark: e.target.value })} placeholder="Enter landmark" />
                      </div>
                    </div>
                  </section>

                  {/* ---- 03 Contact Person Details ----------------------------- */}
                  <section className="client-section">
                    <div className="client-section-header cs-amber">
                      <span className="cs-chip"><i className="bi bi-person-badge"></i></span>
                      <div>
                        <div className="cs-title">Contact Person Details</div>
                        <div className="cs-subtitle">Primary contact and communication details</div>
                      </div>
                      <span className="cs-number">03</span>
                    </div>
                    <div className="row g-3">
                      <div className="col-md-4">
                        <label className="form-label">Contact Person Name <span className="text-danger">*</span></label>
                        <input type="text" className={`form-control ${formErrors.contact_person ? "is-invalid" : ""}`}
                          value={formData.contact_person} onChange={(e) => setFormData({ ...formData, contact_person: e.target.value })} placeholder="Enter contact person name" />
                        {formErrors.contact_person && <div className="invalid-feedback">{formErrors.contact_person}</div>}
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">Phone Number <span className="text-danger">*</span></label>
                        <input type="text" inputMode="numeric" className={`form-control ${formErrors.phone ? "is-invalid" : ""}`}
                          value={formData.phone}
                          onChange={(e) => setFormData({ ...formData, phone: e.target.value.replace(/\D/g, "").slice(0, 13) })}
                          placeholder="Enter 10-digit phone number" maxLength={13} />
                        {formErrors.phone && <div className="invalid-feedback">{formErrors.phone}</div>}
                      </div>
                      <div className="col-md-4">
                        <label className="form-label">Email ID <span className="text-danger">*</span></label>
                        <input type="email" className={`form-control ${formErrors.email ? "is-invalid" : ""}`}
                          value={formData.email} onChange={(e) => setFormData({ ...formData, email: e.target.value })} placeholder="Enter email id" />
                        {formErrors.email && <div className="invalid-feedback">{formErrors.email}</div>}
                      </div>
                    </div>
                  </section>

                  {/* ---- 04 Client Information Status -------------------------- */}
                  <section className="client-section">
                    <div className="client-section-header cs-violet">
                      <span className="cs-chip"><i className="bi bi-toggle-on"></i></span>
                      <div>
                        <div className="cs-title">Client Information Status</div>
                        <div className="cs-subtitle">Current status and remarks</div>
                      </div>
                      <span className="cs-number">04</span>
                    </div>
                    <div className="row g-3">
                      <div className="col-md-3">
                        <label className="form-label">Status</label>
                        <select className="form-select" value={formData.status}
                          onChange={(e) => setFormData({ ...formData, status: e.target.value })}>
                          <option value="Active">Active</option>
                          <option value="Inactive">Inactive</option>
                        </select>
                      </div>
                      <div className="col-md-9">
                        <label className="form-label">Remarks</label>
                        <textarea className="form-control" rows={1} style={{ resize: "none" }}
                          value={formData.remarks} onChange={(e) => setFormData({ ...formData, remarks: e.target.value })}
                          placeholder="Enter remarks (optional)" maxLength={255}></textarea>
                      </div>
                    </div>
                  </section>

                </div>
                <div className="client-form-footer">
                  <button type="button" className="btn btn-outline-secondary px-4" onClick={() => setShowForm(false)}>Cancel</button>
                  <button type="submit" className="btn btn-primary px-4" disabled={isSubmitting}>
                    {isSubmitting ? "Saving..." : editing ? "Update Client" : "Save Client"}
                  </button>
                </div>
              </form>
            </div>
          </div>
        </div>
      )}

      {detail && (
        <div className="modal d-block client-form-backdrop" tabIndex="-1">
          <div className="modal-dialog client-detail-dialog">
            <div className="modal-content client-detail-content">

              <div className="client-form-header">
                <div>
                  <h5 className="client-form-title">Client Details</h5>
                </div>
                <button type="button" className="btn-close" onClick={() => setDetail(null)}></button>
              </div>

              <div className="client-detail-body">

                {/* Identity banner: logo, name, code, status */}
                <div className="client-identity-banner">
                  <div className="client-identity-logo" title={detail.logo_path ? "Client logo" : "No logo uploaded"}>
                    {detail.logo_path ? (
                      <img src={logoUrl(detail.logo_path)} alt="Client logo" />
                    ) : (
                      <i className="bi bi-building"></i>
                    )}
                  </div>
                  <div className="flex-grow-1 min-width-0">
                    <div className="client-identity-name">{detail.client_name}</div>
                    <div className="d-flex align-items-center gap-2 flex-wrap mt-1">
                      <span className="badge bg-light text-dark border font-monospace">{detail.client_code}</span>
                      {detail.status === "Active"
                        ? <span className="badge-status-active"><i className="bi bi-check-circle-fill me-1"></i>Active</span>
                        : <span className="badge-status-inactive"><i className="bi bi-x-circle-fill me-1"></i>Inactive</span>}
                    </div>
                  </div>
                </div>

                {/* 01 Client Information */}
                <div className="client-detail-block">
                  <div className="client-detail-block-title"><span className="detail-chip blue"><i className="bi bi-person-vcard"></i></span>Client Information</div>
                  <div className="row g-3">
                    <div className="col-md-6">
                      <div className="client-detail-label">GST Number</div>
                      <div className="client-detail-value">{detail.gst_number || "—"}</div>
                    </div>
                  </div>
                </div>

                {/* 02 Address Information */}
                <div className="client-detail-block">
                  <div className="client-detail-block-title"><span className="detail-chip green"><i className="bi bi-geo-alt"></i></span>Address Information</div>
                  <div className="row g-3">
                    <div className="col-12">
                      <div className="client-detail-label">Address</div>
                      <div className="client-detail-value">{[detail.address_line_1, detail.address_line_2].filter(Boolean).join(", ") || "—"}</div>
                    </div>
                    <div className="col-md-6">
                      <div className="client-detail-label">City</div>
                      <div className="client-detail-value">{detail.city || "—"}</div>
                    </div>
                    <div className="col-md-6">
                      <div className="client-detail-label">District</div>
                      <div className="client-detail-value">{detail.district || "—"}</div>
                    </div>
                    <div className="col-md-6">
                      <div className="client-detail-label">State</div>
                      <div className="client-detail-value">{detail.state || "—"}</div>
                    </div>
                    <div className="col-md-6">
                      <div className="client-detail-label">PIN Code</div>
                      <div className="client-detail-value">{detail.pincode || "—"}</div>
                    </div>
                    <div className="col-md-6">
                      <div className="client-detail-label">Police Station</div>
                      <div className="client-detail-value">{detail.police_station || "—"}</div>
                    </div>
                    <div className="col-md-6">
                      <div className="client-detail-label">Landmark</div>
                      <div className="client-detail-value">{detail.landmark || "—"}</div>
                    </div>
                  </div>
                </div>

                {/* 03 Contact Person */}
                <div className="client-detail-block">
                  <div className="client-detail-block-title"><span className="detail-chip amber"><i className="bi bi-telephone"></i></span>Contact Person Details</div>
                  <div className="row g-3">
                    <div className="col-md-4">
                      <div className="client-detail-label">Contact Person</div>
                      <div className="client-detail-value">{detail.contact_person || "—"}</div>
                    </div>
                    <div className="col-md-4">
                      <div className="client-detail-label">Phone</div>
                      <div className="client-detail-value">{detail.phone || "—"}</div>
                    </div>
                    <div className="col-md-4">
                      <div className="client-detail-label">Email</div>
                      <div className="client-detail-value">{detail.email || "—"}</div>
                    </div>
                  </div>
                </div>

                {/* 04 Status & Remarks */}
                <div className="client-detail-block">
                  <div className="client-detail-block-title"><span className="detail-chip violet"><i className="bi bi-clipboard-check"></i></span>Status &amp; Remarks</div>
                  <div className="row g-3">
                    <div className="col-md-6">
                      <div className="client-detail-label">Status</div>
                      <div className="client-detail-value">
                        {detail.status === "Active"
                          ? <span className="badge-status-active"><i className="bi bi-check-circle-fill me-1"></i>Active</span>
                          : <span className="badge-status-inactive"><i className="bi bi-x-circle-fill me-1"></i>Inactive</span>}
                      </div>
                    </div>
                    <div className="col-md-6">
                      <div className="client-detail-label">Remarks</div>
                      <div className="client-detail-value">{detail.remarks || "—"}</div>
                    </div>
                  </div>
                </div>

                {/* Login Accounts */}
                <div className="client-detail-block">
                  <div className="client-detail-block-title"><span className="detail-chip teal"><i className="bi bi-person-badge"></i></span>Login Accounts</div>
                  {(detail.linked_users || []).length === 0 ? (
                    <div className="client-detail-value text-muted">No linked logins</div>
                  ) : (
                    (detail.linked_users || []).map((u) => (
                      <div key={u.id} className="client-login-row">
                        <span className={`badge ${u.status === "Active" ? "bg-success-subtle text-success" : "bg-secondary-subtle text-secondary"} border me-1`}>
                          {u.username} ({u.status})
                        </span>
                        {u.must_change_password === true && (
                          <span className="badge bg-warning-subtle text-warning-emphasis border me-1">Temporary password pending</span>
                        )}
                        {canResetPassword && (
                          <button className="btn btn-sm btn-link text-warning p-0 ms-1" title={`Reset password for ${u.username}`}
                            onClick={() => setResetTarget(u)}>
                            <i className="bi bi-key"></i> Reset
                          </button>
                        )}
                      </div>
                    ))
                  )}
                  {(detail.linked_users || []).length === 0 && canCreate && (
                    <div className="mt-2">
                      {!showLoginForm ? (
                        <button className="btn btn-sm btn-outline-primary" onClick={() => setShowLoginForm(true)}>
                          <i className="bi bi-key me-1"></i>Create Login Account
                        </button>
                      ) : (
                        <form onSubmit={handleCreateLogin} className="border rounded p-3 bg-light">
                          <div className="mb-2">
                            <label className="form-label">Username *</label>
                            <input type="text" className="form-control form-control-sm" value={loginData.username}
                              onChange={(e) => setLoginData({ ...loginData, username: e.target.value })} placeholder="min 3 characters" />
                          </div>
                          <div className="mb-2">
                            <label className="form-label">Email</label>
                            <input type="email" className="form-control form-control-sm" value={loginData.email}
                              onChange={(e) => setLoginData({ ...loginData, email: e.target.value })} />
                          </div>
                          <div className="mb-2">
                            <label className="form-label">Password *</label>
                            <input type="password" className="form-control form-control-sm" value={loginData.password}
                              onChange={(e) => setLoginData({ ...loginData, password: e.target.value })} placeholder="min 6 characters" />
                          </div>
                          <div className="d-flex gap-2">
                            <button type="submit" className="btn btn-sm btn-primary" disabled={isCreatingLogin}>
                              {isCreatingLogin ? "Creating..." : "Create (CLIENT role)"}
                            </button>
                            <button type="button" className="btn btn-sm btn-outline-secondary" onClick={() => setShowLoginForm(false)}>Cancel</button>
                          </div>
                        </form>
                      )}
                    </div>
                  )}
                </div>

              </div>
              <div className="client-form-footer">
                <button className="btn btn-outline-secondary px-4" onClick={() => setDetail(null)}>Close</button>
                {canDeactivate && detail.status === "Active" && (
                  <button className="btn btn-outline-danger px-4" onClick={() => handleDeactivate(detail)}>Deactivate</button>
                )}
                {canUpdate && <button className="btn btn-primary px-4" onClick={() => { setDetail(null); openEdit(detail); }}>Edit</button>}
              </div>
            </div>
          </div>
        </div>
      )}

      {resetTarget && (
        <ResetPasswordModal
          userId={resetTarget.id}
          username={resetTarget.username}
          onClose={() => setResetTarget(null)}
          onSuccess={async (message) => {
            setResetTarget(null);
            showAlert("success", message);
            if (detail) {
              const refreshed = await ClientService.getClientById(detail.id);
              if (refreshed.success) setDetail(refreshed.data);
            }
          }}
          onError={(message) => showAlert("danger", message)}
        />
      )}
    </div>
  );
};

export default ClientMaster;
